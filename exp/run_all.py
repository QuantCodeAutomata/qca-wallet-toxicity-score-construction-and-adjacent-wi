def exp1(score_window: Dict, val_window: Dict) -> Dict:
    """EXP1 – Wallet toxicity scoring and persistence."""
    _tprint("EXP1 ▸ scoring wallets on July 1–10 ...")

    # Downsample block states from 2 s to 30 s for fast markout computation
    score_bs_ds = _downsample_bs(score_window["block_states"])
    val_bs_ds = _downsample_bs(val_window["block_states"])

    scores_t1 = compute_wallet_scores(
        score_window["orders"], score_bs_ds, min_orders=MIN_ORDERS
    )
    if scores_t1.empty:
        _tprint("EXP1 ✘ no qualifying wallets – skipping")
        return {}

    _tprint(f"EXP1 ▸ {len(scores_t1)} wallets scored")
    cohort = get_toxic_cohort(scores_t1, top_fraction=0.10)
    _tprint(f"EXP1 ▸ toxic cohort size: {len(cohort)}")

    # ── Persistence: score in validation window ───────────────────────────
    scores_t2 = compute_wallet_scores(
        val_window["orders"], val_bs_ds, min_orders=MIN_ORDERS
    )

    if not scores_t2.empty:
        s1 = scores_t1.set_index("wallet")["alpha_w"]
        s2 = scores_t2.set_index("wallet")["alpha_w"]
        rho, p_rho = spearman_correlation(s1, s2)
        _tprint(f"EXP1 ▸ Spearman ρ = {rho:.4f}  p = {p_rho:.4f}")
    else:
        rho, p_rho = np.nan, np.nan
        _tprint("EXP1 ▸ insufficient wallets in validation window")

    # ── Decile markouts ───────────────────────────────────────────────────
    decile_mk = compute_decile_markouts(
        scores_t1["wallet"].tolist(),
        scores_t1,
        val_window["orders"],
        val_bs_ds,
    )

    # ── Participation persistence ─────────────────────────────────────────
    pers = participation_persistence(cohort, val_window["orders"])
    _tprint(f"EXP1 ▸ participation persistence = {pers:.4f}")

    # ── Peer-adjusted scores ──────────────────────────────────────────────
    peer_scores = compute_peer_adjusted_scores(
        score_window["orders"], score_bs_ds, min_orders=MIN_ORDERS
    )
    _tprint(f"EXP1 ▸ peer-adjusted: {len(peer_scores)} wallets")

    # ── Save ──────────────────────────────────────────────────────────────
    summary = pd.DataFrame({
        "metric": [
            "Spearman rho", "p-value (rho)", "Participation persistence",
            "Wallets scored (t1)", "Wallets scored (t2)",
            "Toxic cohort size", "Peer-adjusted wallets",
        ],
        "value": [
            f"{rho:.4f}", f"{p_rho:.4f}", f"{pers:.4f}",
            len(scores_t1), len(scores_t2) if not scores_t2.empty else 0,
            len(cohort), len(peer_scores),
        ],
    })
    summary.to_csv(os.path.join(RESULTS_DIR, "exp1_summary.csv"), index=False)

    if not decile_mk.empty:
        fig, ax = plt.subplots(figsize=(7, 4))
        grps = decile_mk["group"].values
        means = decile_mk["mean_markout"].values
        ax.bar(grps, means, color="steelblue", alpha=0.75)
        ax.axhline(0, color="k", linewidth=0.8, linestyle="--")
        ax.set_xlabel("Score decile (t1)")
        ax.set_ylabel("Mean markout bps (t2)")
        ax.set_title("EXP1 – Decile markout persistence (July 2026)")
        fig.tight_layout()
        fig.savefig(os.path.join(RESULTS_DIR, "exp1_decile_markouts.png"), dpi=100)
        plt.close(fig)

    _append_md(
        "EXP1: Wallet Toxicity Persistence",
        summary.to_markdown(index=False),
    )
    print(summary.to_string(index=False))
    return {"cohort": cohort, "scores_t1": scores_t1,
            "scores_t2": scores_t2, "peer_scores": peer_scores}


