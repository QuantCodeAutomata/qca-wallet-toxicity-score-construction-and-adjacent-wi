def exp2(
    fit_window: Dict, eval_window: Dict, cohort: List[str]
) -> Tuple[pd.DataFrame, Dict, Dict]:
    """EXP2 – Forecasting race: anonymous vs identity Ridge."""
    _tprint("EXP2 ▸ building feature matrices (fit: July 11–20, eval: July 21–27) ...")

    train_fm = _build_fm(fit_window, FIT_START, FIT_END, cohort)
    eval_fm = _build_fm(eval_window, EVAL_START, EVAL_END, cohort)

    _tprint("EXP2 ▸ running forecasting experiment ...")
    results = run_forecasting_experiment(train_fm, eval_fm, HORIZONS_S)

    _tprint("EXP2 ▸ results:")
    print(results.to_string(index=False))

    results.to_csv(os.path.join(RESULTS_DIR, "exp2_forecasting_race.csv"), index=False)

    # Figure: R2 by horizon
    fig, axes = plt.subplots(1, 2, figsize=(10, 4))
    ax1, ax2 = axes

    x = np.arange(len(HORIZONS_S))
    w = 0.35
    if not results.empty:
        r2_b = results["r2_bench"].fillna(0).values
        r2_i = results["r2_identity"].fillna(0).values
        ax1.bar(x - w / 2, r2_b, w, label="Benchmark (anon)", color="steelblue")
        ax1.bar(x + w / 2, r2_i, w, label="Identity", color="darkorange")
        ax1.set_xticks(x)
        ax1.set_xticklabels([f"{h}s" for h in HORIZONS_S])
        ax1.set_ylabel("OOS R²")
        ax1.set_title("R² by horizon")
        ax1.legend()

        dr2 = results["delta_r2"].fillna(0).values
        ax2.bar(x, dr2, color="green", alpha=0.75)
        ax2.set_xticks(x)
        ax2.set_xticklabels([f"{h}s" for h in HORIZONS_S])
        ax2.set_ylabel("ΔR² (identity − anon)")
        ax2.set_title("Identity increment")
        ax2.axhline(0, color="k", linewidth=0.8)

    fig.suptitle("EXP2 – Forecasting Race (July 2026)")
    fig.tight_layout()
    fig.savefig(os.path.join(RESULTS_DIR, "exp2_forecasting_race.png"), dpi=100)
    plt.close(fig)

    _append_md(
        "EXP2: Forecasting Race",
        results.to_markdown(index=False),
    )
    return results, train_fm, eval_fm


