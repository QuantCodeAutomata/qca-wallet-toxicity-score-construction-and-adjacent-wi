def exp3(
    cohort: List[str],
    scored_wallets: pd.DataFrame,
    train_fm: Dict[str, pd.DataFrame],
    eval_fm: Dict[str, pd.DataFrame],
    real_results: pd.DataFrame,
) -> None:
    """EXP3 – Placebo cohort test (20 draws)."""
    _tprint("EXP3 ▸ running 20 placebo draws ...")

    placebo_df = run_placebo_analysis(
        n_draws=20,
        toxic_cohort=cohort,
        scored_wallets=scored_wallets,
        train_data=train_fm,
        eval_data=eval_fm,
        horizons=HORIZONS_S,
        seed=SEED,
    )
    placebo_df.to_csv(os.path.join(RESULTS_DIR, "exp3_placebo_draws.csv"), index=False)

    rows = []
    for h in HORIZONS_S:
        real_row = real_results[real_results["horizon"] == h]
        real_dr2 = float(real_row["delta_r2"].values[0]) if not real_row.empty else np.nan

        p_draws = placebo_df[placebo_df["horizon"] == h]["delta_r2"]
        p_val = compute_rank_pvalue(real_dr2, p_draws) if len(p_draws) > 0 else np.nan

        rows.append({
            "horizon": h,
            "real_delta_r2": real_dr2,
            "placebo_mean_delta_r2": float(p_draws.mean()) if len(p_draws) > 0 else np.nan,
            "rank_p_value": p_val,
        })

    pval_df = pd.DataFrame(rows)
    pval_df.to_csv(os.path.join(RESULTS_DIR, "exp3_placebo_pvalues.csv"), index=False)
    _tprint("EXP3 ▸ placebo p-values:")
    print(pval_df.to_string(index=False))

    # Figure: histogram of placebo delta_R2 vs real
    fig, axes = plt.subplots(1, len(HORIZONS_S), figsize=(12, 4))
    for ax, h in zip(axes, HORIZONS_S):
        p_draws = placebo_df[placebo_df["horizon"] == h]["delta_r2"].dropna()
        real_row = real_results[real_results["horizon"] == h]
        real_dr2 = float(real_row["delta_r2"].values[0]) if not real_row.empty else np.nan

        if len(p_draws) > 0:
            ax.hist(p_draws, bins=10, color="grey", alpha=0.7, label="Placebo")
        if np.isfinite(real_dr2):
            ax.axvline(real_dr2, color="red", linewidth=2, label=f"Real ΔR²={real_dr2:.4f}")
        ax.set_title(f"{h}s horizon")
        ax.set_xlabel("ΔR²")
        ax.legend(fontsize=7)

    fig.suptitle("EXP3 – Placebo distribution vs real identity increment")
    fig.tight_layout()
    fig.savefig(os.path.join(RESULTS_DIR, "exp3_placebo_hist.png"), dpi=100)
    plt.close(fig)

    _append_md(
        "EXP3: Placebo Test",
        pval_df.to_markdown(index=False),
    )


