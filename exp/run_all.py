def _fills_to_orders(fills: pd.DataFrame, coin_col: str = "market") -> pd.DataFrame:
    """Convert taker fills into an orders-compatible DataFrame."""
    takers = fills[fills["is_taker"]].copy() if "is_taker" in fills.columns else fills.copy()
    takers = takers.rename(columns={"fill_time": "event_time"})
    takers["direction"] = takers["side"].map({"buy": 1, "sell": -1}).fillna(0).astype(int)
    takers["notional"] = takers["notional"].abs()
    takers["is_twap"] = takers.get("is_twap", False)
    takers["is_liquidation"] = takers.get("is_liquidation", False)
    return takers


def exp5(
    fit_window: Dict, eval_window: Dict, cohort: List[str]
) -> None:
    """EXP5 – Fill diagnostics: fill-time, side-revealed, no-TWAP restriction."""
    _tprint("EXP5 ▸ fill diagnostic variants ...")

    eval_fills = eval_window["fills"]
    eval_fills_no_twap = eval_fills[~eval_fills["is_twap"]] if "is_twap" in eval_fills else eval_fills

    rows = []
    for label, fills_src in [
        ("fill_arrival", eval_fills),
        ("side_revealed", eval_fills),
        ("no_twap_parent", eval_fills_no_twap),
    ]:
        # Replace orders in eval_window with fill-derived orders
        fill_orders = _fills_to_orders(fills_src)
        eval_mod = dict(eval_window)
        eval_mod["orders"] = fill_orders

        e_fm = _build_fm(eval_mod, EVAL_START, EVAL_END, cohort)

        # For side_revealed: add direction as an explicit feature
        extra_feat_cols = list(_ANON_COLS)
        if label == "side_revealed":
            for coin, df in e_fm.items():
                # Approximate direction signal from hotFlow1s sign
                df["dir_signal"] = np.sign(df.get("hotFlow1s", 0))
            extra_feat_cols = list(_ANON_COLS) + ["dir_signal"]

        # Use train_fm from exp2 (already built without modification)
        t_fm = _build_fm(fit_window, FIT_START, FIT_END, cohort)
        if label == "side_revealed":
            for coin, df in t_fm.items():
                df["dir_signal"] = np.sign(df.get("hotFlow1s", 0))

        # Evaluate anonymous model
        full_feat = [c for c in extra_feat_cols + _IDEN_COLS
                     if c in list(t_fm.values())[0].columns]
        r2, _, _ = _quick_ridge_eval(t_fm, e_fm, full_feat, 1.0)
        rows.append({"variant": label, "horizon": 1.0, "r2": r2})

    diag_df = pd.DataFrame(rows)
    diag_df.to_csv(os.path.join(RESULTS_DIR, "exp5_fill_diagnostics.csv"), index=False)
    _tprint("EXP5 ▸ fill diagnostic results:")
    print(diag_df.to_string(index=False))

    fig, ax = plt.subplots(figsize=(6, 4))
    ax.bar(diag_df["variant"], diag_df["r2"], color=["steelblue", "darkorange", "green"])
    ax.set_ylabel("OOS R² (1 s horizon)")
    ax.set_title("EXP5 – Fill diagnostic variants")
    ax.axhline(0, color="k", linewidth=0.5)
    plt.xticks(rotation=15, ha="right")
    fig.tight_layout()
    fig.savefig(os.path.join(RESULTS_DIR, "exp5_fill_diagnostics.png"), dpi=100)
    plt.close(fig)

    _append_md("EXP5: Fill Diagnostics", diag_df.to_markdown(index=False))


