def _generate_window(start: str, end: str, seed: int = SEED) -> Dict:
    """Generate block states, orders, and fills for a date window."""
    bs = generate_block_states(start, end, COINS, seed=seed)
    orders = generate_aggressive_orders(
        start, end, COINS, n_wallets=N_WALLETS, seed=seed
    )
    fills = generate_fills(orders, seed=seed)
    return {"block_states": bs, "orders": orders, "fills": fills}


def _downsample_bs(bs: pd.DataFrame, factor: int = 15) -> pd.DataFrame:
    """Reduce block-state resolution by keeping every *factor*-th row per market.

    The default factor=15 converts 2 s blocks to 30 s resolution, staying
    well within the 60 s pre-staleness limit used by ``compute_markout``.
    Used to speed up wallet-scoring without affecting feature building.
    """
    frames = [grp.iloc[::factor].copy() for _, grp in bs.groupby("market")]
    return pd.concat(frames, ignore_index=True) if frames else bs.copy()


def _build_fm(
    window: Dict,
    start: str,
    end: str,
    cohort: List[str],
    freq_ms: int = GRID_FREQ_MS,
    embargo_ms: int = 0,
) -> Dict[str, pd.DataFrame]:
    """Build feature matrix dict for a window at *freq_ms* resolution."""
    grid = build_100ms_grid(
        pd.Timestamp(start), pd.Timestamp(end), freq_ms=freq_ms
    )
    return build_feature_matrix(
        grid=grid,
        block_states=window["block_states"],
        orders=window["orders"],
        cohort=cohort,
        coins=COINS,
        horizons_s=HORIZONS_S,
        embargo_ms=embargo_ms,
    )


def _pool_fm(fm: Dict[str, pd.DataFrame], horizon_col: str,
             feat_cols: List[str]) -> Tuple[pd.DataFrame, pd.Series, pd.Series]:
    """Pool multi-coin feature matrix; return (X, y, dates)."""
    frames = []
    for df in fm.values():
        needed = feat_cols + ["coin", "date", horizon_col]
        available = [c for c in needed if c in df.columns]
        sub = df[available].dropna(subset=[c for c in [horizon_col] + feat_cols
                                           if c in df.columns])
        frames.append(sub)
    if not frames:
        empty = pd.DataFrame()
        return empty, pd.Series(dtype=float), pd.Series(dtype=object)
    pooled = pd.concat(frames, ignore_index=True)
    fcols_avail = [c for c in feat_cols if c in pooled.columns]
    X = pooled[fcols_avail + ["coin"]].copy()
    y = pooled[horizon_col].copy()
    dates = pooled["date"].copy()
    return X, y, dates


def _quick_ridge_eval(
    train_fm: Dict[str, pd.DataFrame],
    eval_fm: Dict[str, pd.DataFrame],
    feat_cols: List[str],
    horizon: float,
) -> Tuple[float, np.ndarray, np.ndarray]:
    """Fit ridge, evaluate; return (r2, y_ev, yhat)."""
    hcol = f"{horizon}s"
    X_tr, y_tr, dates_tr = _pool_fm(train_fm, hcol, feat_cols)
    X_ev, y_ev, _ = _pool_fm(eval_fm, hcol, feat_cols)

    if X_tr.empty or X_ev.empty or y_tr.empty or y_ev.empty:
        empty = np.array([])
        return np.nan, empty, empty

    X_tr_d = add_coin_intercepts(X_tr, "coin")
    X_ev_d = add_coin_intercepts(X_ev, "coin")
    # Align columns
    for c in X_tr_d.columns:
        if c not in X_ev_d.columns:
            X_ev_d[c] = 0.0
    X_ev_d = X_ev_d[X_tr_d.columns]

    alpha = expanding_day_cv_ridge(X_tr_d, y_tr, dates_tr, RIDGE_ALPHAS)
    X_tr_s, X_ev_s, _, _ = standardize_features(X_tr_d, X_ev_d)
    model = fit_ridge(X_tr_s, y_tr, alpha)
    yhat = predict(model, X_ev_s)
    r2 = compute_oos_r2(y_ev.values, yhat)
    return r2, y_ev.values, yhat


