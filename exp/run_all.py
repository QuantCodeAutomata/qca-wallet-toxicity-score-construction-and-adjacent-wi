# ─────────────────────────────── EXP 7 ───────────────────────────────────────


def exp7(
    train_fm: Dict[str, pd.DataFrame],
    eval_fm: Dict[str, pd.DataFrame],
) -> None:
    """EXP7 – Payoff diagnostic: payoff statistic across budgets."""
    _tprint("EXP7 ▸ computing payoff statistics ...")

    budgets = [0.05, 0.10, 0.25, 0.50, 1.0]
    all_rows = []

    for h in HORIZONS_S:
        hcol = f"{h}s"
        X_tr_a, y_tr, dates_tr = _pool_fm(train_fm, hcol, _ANON_COLS)
        X_ev_a, y_ev, _ = _pool_fm(eval_fm, hcol, _ANON_COLS)
        X_tr_f, _, _ = _pool_fm(train_fm, hcol, _ANON_COLS + _IDEN_COLS)
        X_ev_f, _, _ = _pool_fm(eval_fm, hcol, _ANON_COLS + _IDEN_COLS)

        if any(df.empty for df in [X_tr_a, X_ev_a, X_tr_f, X_ev_f]) or y_ev.empty:
            continue

        X_tr_a_d = add_coin_intercepts(X_tr_a, "coin")
        X_ev_a_d = add_coin_intercepts(X_ev_a, "coin")
        X_tr_f_d = add_coin_intercepts(X_tr_f, "coin")
        X_ev_f_d = add_coin_intercepts(X_ev_f, "coin")

        for c in X_tr_a_d.columns:
            if c not in X_ev_a_d.columns:
                X_ev_a_d[c] = 0.0
        X_ev_a_d = X_ev_a_d[X_tr_a_d.columns]
        for c in X_tr_f_d.columns:
            if c not in X_ev_f_d.columns:
                X_ev_f_d[c] = 0.0
        X_ev_f_d = X_ev_f_d[X_tr_f_d.columns]

        alpha_a = expanding_day_cv_ridge(X_tr_a_d, y_tr, dates_tr, RIDGE_ALPHAS)
        alpha_f = expanding_day_cv_ridge(X_tr_f_d, y_tr, dates_tr, RIDGE_ALPHAS)

        X_tr_a_s, X_ev_a_s, _, _ = standardize_features(X_tr_a_d, X_ev_a_d)
        X_tr_f_s, X_ev_f_s, _, _ = standardize_features(X_tr_f_d, X_ev_f_d)

        m_anon = fit_ridge(X_tr_a_s, y_tr, alpha_a)
        m_full = fit_ridge(X_tr_f_s, y_tr, alpha_f)

        yhat_anon = predict(m_anon, X_ev_a_s)
        yhat_full = predict(m_full, X_ev_f_s)

        y_arr = y_ev.values
        tbl = payoff_table(
            pd.Series(y_arr),
            {"anonymous": yhat_anon, "identity": yhat_full},
            budgets,
        )
        tbl.columns = [f"bud={b}" for b in tbl.columns]
        tbl.insert(0, "horizon", h)
        all_rows.append(tbl.reset_index())

    if all_rows:
        payoff_df = pd.concat(all_rows, ignore_index=True)
        payoff_df.to_csv(os.path.join(RESULTS_DIR, "exp7_payoff.csv"), index=False)
        _tprint("EXP7 ▸ payoff table:")
        print(payoff_df.to_string(index=False))

        # Plot for 1s horizon
        h1 = payoff_df[payoff_df["horizon"] == 1.0]
        if not h1.empty:
            bud_cols = [c for c in h1.columns if c.startswith("bud=")]
            budget_vals = [float(c.split("=")[1]) for c in bud_cols]
            fig, ax = plt.subplots(figsize=(7, 4))
            for _, row in h1.iterrows():
                payoffs = [float(row[c]) for c in bud_cols]
                ax.plot(budget_vals, payoffs, "o-", label=str(row.get("model", row.name)))
            ax.set_xlabel("Budget fraction")
            ax.set_ylabel("Payoff (bps)")
            ax.set_title("EXP7 – Payoff vs signal budget (1 s horizon)")
            ax.legend()
            ax.axhline(0, color="k", linewidth=0.5)
            fig.tight_layout()
            fig.savefig(os.path.join(RESULTS_DIR, "exp7_payoff.png"), dpi=100)
            plt.close(fig)

        _append_md("EXP7: Payoff Diagnostic", payoff_df.to_markdown(index=False))


